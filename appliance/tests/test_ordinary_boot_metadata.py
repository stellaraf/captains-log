"""Pinned AIDE DB grammar, real-byte provenance and hostile row coverage."""
import base64
import copy
import gzip
import hashlib
from pathlib import Path
from types import SimpleNamespace
import unittest
from unittest.mock import patch

from nebulalog_manager import ordinary_boot_metadata as metadata
from nebulalog_manager.common import Refused


def b64(value):
    return base64.b64encode(value).decode()


def fixture_row(path):
    link = path == '/etc/os-release'
    efi = path in metadata.EFI
    label = b'system_u:object_r:dosfs_t:s0' if efi else b'system_u:object_r:etc_t:s0'
    return dict(zip(metadata.FIELDS, (
        path, '../usr/lib/os-release' if link else '0',
        '120777' if link else '100700' if efi else '100644', '0', '0', '21' if link else '7',
        '1760000000', '1750000000', '73', '1',
        str(metadata.EFI_MASK if efi else metadata.SYMLINK_MASK if link else metadata.REGULAR_MASK),
        '0' if link or efi else 'POSIX,' + b64(b'user::rw-\ngroup::r--\nother::r--\n') + ',0',
        '0' if link else b64(hashlib.sha512(b'fixture').digest()), b64(label),
        '1,security.selinux,' + b64(label + b'\0'),
    )))


def text_database(rows=None):
    if rows is None:
        rows = [fixture_row(path) for path in sorted(metadata.TARGETS)]
    header = [b'@@begin_db', b'# This file was generated by Aide, version 0.19.2',
              b'# Time of generation was 2026-10-15 17:00:52 +0000', metadata.SPEC]
    body = [' '.join(row[field] for field in metadata.FIELDS).encode('ascii') for row in rows]
    return b'\n'.join(header + body + [b'@@end_db', b''])


def compressed(text=None):
    return gzip.compress(text_database() if text is None else text, mtime=0)


def parse(raw):
    return metadata.parse_database(raw, expected_sha256=hashlib.sha256(raw).hexdigest())


class MetadataDatabaseTests(unittest.TestCase):
    def changed_row(self, field, value, path='/etc/issue'):
        rows = [fixture_row(name) for name in sorted(metadata.TARGETS)]
        next(row for row in rows if row['name'] == path)[field] = value
        return compressed(text_database(rows))

    def assert_refused(self, raw):
        with self.assertRaises(Refused):
            parse(raw)

    def test_exact_rows_keep_seconds_and_full_security_values(self):
        result = parse(compressed())
        self.assertEqual(result['entry_count'], 18)
        self.assertEqual(set(result['rows']), metadata.TARGETS)
        issue = result['rows']['/etc/issue']
        self.assertEqual((issue['inode'], issue['ctime_s'], issue['mtime_s']), (73, 1760000000, 1750000000))
        self.assertNotIn('ctime_ns', issue)
        self.assertEqual(issue['sha512'], hashlib.sha512(b'fixture').hexdigest())
        self.assertEqual(base64.b64decode(issue['xattrs']['security.selinux']),
                         base64.b64decode(issue['selinux']) + b'\0')
        link = result['rows']['/etc/os-release']
        self.assertEqual(link['target'], '../usr/lib/os-release')
        self.assertIsNone(link['sha512'])
        self.assertEqual(metadata.REGULAR_MASK, 49394224061)
        self.assertEqual(metadata.EFI_MASK, 49392126909)
        self.assertEqual(metadata.SYMLINK_MASK, 47244643263)

    def test_digest_and_compressed_input_limits_are_mandatory(self):
        raw = compressed()
        for supplied in ('0' * 64, 'A' * 64, None, True, ''):
            with self.subTest(supplied=supplied), self.assertRaises(Refused):
                metadata.parse_database(raw, expected_sha256=supplied)
        with patch.object(metadata, 'MAX_COMPRESSED', len(raw) - 1):
            self.assert_refused(raw)
        with self.assertRaises(Refused):
            metadata.parse_database(bytearray(raw), expected_sha256=hashlib.sha256(raw).hexdigest())

    def test_compressed_integrity_completion_and_single_member(self):
        raw = compressed()
        for bad in (raw[:-1], raw[:10], raw + b'garbage', raw + raw,
                    raw[:-8] + bytes([raw[-8] ^ 1]) + raw[-7:], text_database()):
            with self.subTest(size=len(bad)):
                self.assert_refused(bad)

    def test_streaming_expansion_line_and_entry_limits(self):
        with patch.object(metadata, 'MAX_UNCOMPRESSED', 1024):
            self.assert_refused(compressed())
        with patch.object(metadata, 'MAX_LINE', 50):
            self.assert_refused(compressed())
        with patch.object(metadata, 'MAX_ROWS', 17):
            self.assert_refused(compressed())
        # An oversized line split across decompressor output chunks remains bounded.
        raw = compressed(text_database().replace(b'@@end_db\n', b'/' + b'x' * (metadata.MAX_LINE + 1) + b'\n@@end_db\n'))
        self.assert_refused(raw)

    def test_exact_header_spec_version_and_metadata(self):
        original = text_database()
        mutations = [(b'@@begin_db', b'@@begin_db extra'), (b'version 0.19.2', b'version 0.19.3'),
                     (metadata.SPEC, metadata.SPEC + b' unknown'), (b'name lname perm', b'name perm lname'),
                     (b'# Time of generation was', b'# unrecognized metadata'),
                     (b'2026-10-15', b'2026-13-15'), (b'+0000', b'+9999'),
                     (metadata.SPEC, metadata.SPEC + b'\n' + metadata.SPEC)]
        for before, after in mutations:
            with self.subTest(after=after):
                self.assert_refused(compressed(original.replace(before, after, 1)))
        for cutoff in range(4):
            self.assert_refused(compressed(b'\n'.join(original.splitlines()[:cutoff]) + b'\n'))

    def test_end_marker_trailing_data_and_comments_are_not_skipped(self):
        original = text_database()
        for text in (original.replace(b'@@end_db\n', b''), original + b'\n', original + b'@@end_db\n',
                     original.replace(b'@@end_db', b'# comment\n@@end_db'), original[:-1],
                     original.replace(b'@@end_db', b'@@end_db extra')):
            self.assert_refused(compressed(text))

    def test_duplicate_and_missing_rows(self):
        rows = [fixture_row(path) for path in sorted(metadata.TARGETS)]
        self.assert_refused(compressed(text_database(rows[:-1])))
        self.assert_refused(compressed(text_database(rows + [rows[0]])))
        extra = fixture_row('/usr/share/other')
        self.assert_refused(compressed(text_database(rows + [extra, extra])))

    def test_canonical_filename_encoding_and_duplicate_alias(self):
        rows = [fixture_row(path) for path in sorted(metadata.TARGETS)]
        extra = fixture_row('/usr/share/with%20space%25%2C%FF')
        self.assertEqual(parse(compressed(text_database(rows + [extra])))['entry_count'], 19)
        for name in ('/etc/%69ssue', '/etc/%2fissue', '/etc/../issue', '/etc//issue',
                     '/etc/issue/', '/etc/%00issue', '/etc/issue%', '/etc/issue#'):
            self.assert_refused(self.changed_row('name', name))

    def test_noncanonical_and_oversized_numbers(self):
        for field in ('ctime', 'mtime', 'inode', 'size', 'lcount', 'uid', 'gid', 'attr'):
            for value in ('+1', '-1', '01', '1.0', '9' * 21, '18446744073709551616'):
                with self.subTest(field=field, value=value):
                    self.assert_refused(self.changed_row(field, value))
        for field, value in (('perm', '0100644'), ('perm', '100648'), ('uid', '4294967296'),
                             ('gid', '4294967296'), ('inode', '0')):
            self.assert_refused(self.changed_row(field, value))

    def test_attribute_mask_exact_for_each_target(self):
        for path in ('/etc/issue', '/etc/os-release', metadata.EFI[0]):
            original = int(fixture_row(path)['attr'])
            for bit in range(46):
                with self.subTest(path=path, bit=bit):
                    self.assert_refused(self.changed_row('attr', str(original ^ (1 << bit)), path))

    def test_target_type_owner_mode_link_count_and_link_target(self):
        for field, value in (('perm', '40755'), ('perm', '100666'), ('perm', '104644'),
                             ('uid', '1'), ('gid', '1'), ('lcount', '2'), ('lname', '/elsewhere')):
            self.assert_refused(self.changed_row(field, value))
        for field, value in (('perm', '120700'), ('lname', '/usr/lib/os-release'), ('sha512', b64(b'x' * 64))):
            self.assert_refused(self.changed_row(field, value, '/etc/os-release'))

    def test_base64_and_security_metadata_validation(self):
        for field in ('sha512', 'selinux'):
            for value in ('!', 'AB==', 'abc', 'AAAA\t'):
                self.assert_refused(self.changed_row(field, value))
        for value in ('0', b64(b'x' * 63), b64(b'x' * 65)):
            self.assert_refused(self.changed_row('sha512', value))
        for field, value in (('selinux', '0'), ('selinux', b64(b'wrong_label')),
                             ('xattrs', '0'), ('acl', '0'), ('acl', 'POSIX,0,0'),
                             ('acl', 'POSIX,' + b64(b'a\0b') + ',0'), ('acl', 'POSIX,!,0')):
            self.assert_refused(self.changed_row(field, value))

    def test_xattr_count_encoding_duplicates_and_empty_values(self):
        label = fixture_row('/etc/issue')['xattrs']
        for value in ('1', '1,security.selinux', '0,extra,0', '257', '01,k,0',
                      label.replace('1,', '2,') + ',' + label.split(',', 1)[1],
                      label.replace('security.selinux', 'security%2Eselinux')):
            self.assert_refused(self.changed_row('xattrs', value))
        value = label.replace('1,', '2,') + ',user.empty,0'
        parsed = parse(self.changed_row('xattrs', value))
        self.assertEqual(parsed['rows']['/etc/issue']['xattrs']['user.empty'], '')

    def test_every_row_is_checked_even_outside_selected_paths(self):
        rows = [fixture_row(path) for path in sorted(metadata.TARGETS)]
        extra = fixture_row('/usr/share/other')
        for field, value in (('inode', '-1'), ('acl', 'broken'), ('sha512', 'bad'), ('xattrs', '1,a')):
            self.assert_refused(compressed(text_database(rows + [{**extra, field: value}])))
        text = text_database(rows + [extra])
        self.assert_refused(compressed(text.replace(b'/usr/share/other ', b'/usr/share/other  ')))

    def test_native_summaries_and_every_other_changed_column(self):
        rows = parse(compressed())['rows']
        cases = [(metadata.EFI[0], 'inode', 'f = ... ..i.. ..  '),
                 ('/etc/issue', 'ctime', 'f = ... .c......  '),
                 ('/etc/os-release', 'ctime', 'l.= ... .c..  ..  ')]
        for path, attribute, summary in cases:
            metadata.validate_change_summary(path, summary, row=rows[path], attribute=attribute)
            for index in range(len(summary)):
                for char in ('+', '-', ':', 'H', 'p', 'X', 'S'):
                    with self.subTest(path=path, index=index, char=char), self.assertRaises(Refused):
                        metadata.validate_change_summary(path, summary[:index] + char + summary[index + 1:],
                                                         row=rows[path], attribute=attribute)
            for bad in (summary + ' ', summary[:-1], summary.replace('c', '.'), None):
                if bad == summary:
                    continue
                with self.assertRaises(Refused):
                    metadata.validate_change_summary(path, bad, row=rows[path], attribute=attribute)
        with self.assertRaises(Refused):
            metadata.validate_change_summary('/etc/elsewhere', cases[1][2], row=rows['/etc/issue'], attribute='ctime')


class AcceptedDatabaseTests(unittest.TestCase):
    def setUp(self):
        self.raw = compressed()
        self.sha = hashlib.sha256(self.raw).hexdigest()
        self.identity = SimpleNamespace(root=Path('/private-test-data'))
        self.reads = []
        def read(path, identity):
            self.reads.append((path, identity))
            return self.raw
        self.manager = SimpleNamespace(guard=lambda: self.identity, _bytes=read)
        self.history = {'original_enrollment': {'database_sha256': self.sha},
                        'head': None, 'database_sha256': self.sha, 'current_database_sha256': self.sha,
                        'pending': None, 'pending_prepared': None, 'history': []}

    def call(self, *, head=None, sha=None, owner=None):
        return metadata.read_accepted_database(self.manager, source_head=head,
                                               source_database_sha256=self.sha if sha is None else sha,
                                               pending_owner=owner)

    def test_live_verified_chain_is_read_twice_and_only_private_database(self):
        with patch('nebulalog_manager.aide_updates.accepted_plan_history', return_value=self.history) as history:
            result = self.call()
        self.assertEqual(history.call_count, 2)
        self.assertEqual(self.reads, [(self.identity.root / 'manager/aide/aide.db.gz', self.identity)])
        self.assertEqual(result['source']['basis'], 'published')
        self.assertIsNone(result['source']['pending_sha256'])

    def test_hash_shaped_claim_cannot_override_verified_chain(self):
        with patch('nebulalog_manager.aide_updates.accepted_plan_history', return_value=self.history):
            for kwargs in ({'sha': 'a' * 64}, {'head': {'id': 'b' * 32, 'sha256': 'c' * 64}}):
                with self.assertRaises(Refused):
                    self.call(**kwargs)
        self.assertEqual(self.reads, [])

    def test_foreign_pending_and_chain_validation_failure_propagate(self):
        with patch('nebulalog_manager.aide_updates.accepted_plan_history', side_effect=Refused('foreign_owner')):
            with self.assertRaisesRegex(Refused, 'foreign_owner'):
                self.call()
        self.assertEqual(self.reads, [])

    def test_owned_ready_copied_output_is_distinct_from_published_input(self):
        old_sha, entry = 'a' * 64, {'id': 'b' * 32, 'sha256': 'c' * 64}
        self.history['database_sha256'] = old_sha
        self.history['pending'] = {'state': 'ready', 'database_sha256': self.sha, 'entry': entry,
                                   'proposed_entry': {'previous': None, 'previous_database_sha256': old_sha}}
        owner = Path('/private-test-data/manager/boot-integrity') / ('d' * 32)
        with patch('nebulalog_manager.aide_updates.accepted_plan_history', return_value=self.history) as history:
            result = self.call(head=entry, owner=owner)
            self.assertEqual(result['source']['basis'], 'owned-ready-output')
            self.assertEqual(result['source']['head'], entry)
            self.assertIsNone(result['source']['observed_head'])
            history.assert_called_with(manager=self.manager, allow_pending_owner=owner, pending_authority=None)
            with self.assertRaises(Refused):
                self.call(head=None, owner=owner)

    def test_wrong_ready_predecessor_unpublished_input_and_race_refuse(self):
        changed = copy.deepcopy(self.history); changed['head'] = {'id': 'e' * 32, 'sha256': 'f' * 64}
        with patch('nebulalog_manager.aide_updates.accepted_plan_history', side_effect=[self.history, changed]):
            with self.assertRaisesRegex(Refused, 'history_changed_during_read'):
                self.call()
        self.history['current_database_sha256'] = 'a' * 64
        with patch('nebulalog_manager.aide_updates.accepted_plan_history', return_value=self.history):
            with self.assertRaises(Refused):
                self.call()

    def test_file_bytes_must_match_actual_chain_database(self):
        self.raw += b'changed'
        with patch('nebulalog_manager.aide_updates.accepted_plan_history', return_value=self.history):
            with self.assertRaisesRegex(Refused, 'database_digest_or_size_mismatch'):
                self.call()


