"""Operation-owned, exactly measured GRUB one-shot and promotion transitions.

The lifecycle caller owns manager/update locks, backup, unlock and service gates.
Callbacks are trusted AIDE integration, never request-supplied authorization.
This module never reboots, deletes a kernel, or declares an appliance accepted.
"""
from __future__ import annotations

import base64
import os
from pathlib import Path
import re
import tempfile
import uuid

from . import kernel_updates as kernel, os_payload as rpm
from .common import Refused, atomic_json, require_linux_root, run
from .host_job_storage import digest, exact, strict_json
from .updates import REQUIRED_CHECKS

ENV = kernel.GRUBENV
TOOL = '/usr/bin/grub2-editenv'
# Native reference: Rocky grub2-tools-minimal-2.06-126.el9_8.rocky.0.3.x86_64.
# This pin alone does not establish native appliance boot qualification.
TOOL_SHA256 = '036832a2af32dfc0bdd976c971079327ac84f4b021e1eeb1bf59c9ff95d11262'
HEADER = b'# GRUB Environment Block\n'
WARNING = b'# WARNING: Do not edit this file by tools other than grub-editenv!!!\n'
PHASES = {'arm': 1, 'abort': 2, 'postboot': 3, 'commit': 4, 'resume': 5}
NAME = re.compile(r'kernel-boot-([a-f0-9]{32})-plan\.json')
PLAN_FIELDS = {'schema', 'kind', 'id', 'phase', 'sequence', 'stage', 'operation_sha256', 'boot_id',
               'running_kernel', 'candidate_stage', 'candidate_plan_sha256', 'installed_sha256',
               'kernel', 'old_kernel', 'candidate_entry', 'old_entry', 'previous', 'before_raw',
               'after_raw', 'files', 'health', 'manifest_sha256'}


def refuse(reason):
    raise Refused('kernel_boot_' + reason)


def boot_id():
    value = Path('/proc/sys/kernel/random/boot_id').read_text().strip()
    try:
        if str(uuid.UUID(value)) != value:
            raise ValueError()
    except (ValueError, AttributeError):
        refuse('invalid_boot_identity')
    return value


def parse_environment(raw):
    """Parse the qualified fixed-size GRUB block without interpreting shell."""
    if not isinstance(raw, bytes) or len(raw) != 1024 or not raw.startswith(HEADER):
        refuse('unqualified_environment_format')
    body = raw[len(HEADER):]
    if body.startswith(WARNING):
        body = body[len(WARNING):]
    entries = {}
    while body and not body.startswith(b'#'):
        line, sep, body = body.partition(b'\n')
        key, equals, value = line.partition(b'=')
        if (not sep or not equals or not re.fullmatch(rb'[A-Za-z_][A-Za-z0-9_]*', key)
                or any(c < 32 or c > 126 for c in value)):
            refuse('invalid_environment_entry')
        name = key.decode('ascii')
        if name in entries:
            refuse('duplicate_environment_entry')
        entries[name] = value.decode('ascii')
    if not body or set(body) != {ord('#')}:
        refuse('invalid_environment_padding')
    return entries


def transition_variables(before, phase, old_entry, candidate_entry, *, observed=None, restored=None):
    """The entire variable map is checked, including unrelated GRUB settings."""
    if before.get('saved_entry') != (candidate_entry if phase == 'resume' else old_entry):
        refuse('recovery_default_not_owned')
    after = dict(before)
    if phase == 'arm':
        if any(before.get(name) not in (None, '') for name in ('prev_saved_entry', 'boot_counter', 'menu_show_once')):
            refuse('competing_boot_control_exists')
        if before.get('boot_success') not in ('0', '1') or before.get('boot_indeterminate') not in ('0', '1', '2'):
            refuse('unqualified_initial_boot_flags')
        if before.get('next_entry') not in (None, ''):
            refuse('another_one_shot_entry_exists')
        after['next_entry'] = candidate_entry
    elif phase == 'abort':
        if before.get('next_entry') != candidate_entry:
            refuse('one_shot_entry_not_owned')
        after.pop('next_entry')
        if restored is not None:
            if (restored.get('next_entry') not in (None, '')
                    or {key: value for key, value in restored.items() if key != 'next_entry'} != after):
                refuse('abort_original_environment_changed')
            after = dict(restored)
    elif phase in {'postboot', 'resume'}:
        if (not isinstance(observed, dict)
                or phase == 'postboot' and before.get('next_entry') != candidate_entry
                or phase == 'resume' and before.get('next_entry') not in (None, '')):
            refuse('armed_boot_evidence_missing')
        if observed.get('next_entry') not in (None, ''):
            refuse('one_shot_entry_not_consumed')
        after.pop('next_entry', None)
        if 'next_entry' in observed:
            after['next_entry'] = ''
        # The qualified 10_reset_boot_success consumer resets success to zero;
        # the vendor user timer may subsequently mark that boot successful.
        # system-update.target's increment writer is not part of this reboot.
        indeterminate = ('0' if before['boot_success'] == '1' else
                         '2' if before['boot_indeterminate'] == '1' else before['boot_indeterminate'])
        if observed.get('boot_success') not in ('0', '1') or observed.get('boot_indeterminate') != indeterminate:
            refuse('unqualified_boot_flag_transition')
        after.update(boot_success=observed['boot_success'], boot_indeterminate=indeterminate)
        if after != observed:
            refuse('unrelated_boot_environment_change')
    elif phase == 'commit':
        if before.get('next_entry') not in (None, ''):
            refuse('one_shot_entry_still_pending')
        after['saved_entry'] = candidate_entry
    else:
        refuse('unknown_transition')
    return after


def _read_json(path):
    return strict_json(rpm.read(path, rpm.MAX_XML))


def _candidate(stage):
    candidate_stage, plan, plan_sha, installed = kernel.load_candidate(stage)
    if (installed.get('plan_sha256') != plan_sha or installed.get('kernel') != plan['kernel']
            or not kernel.KERNEL.fullmatch(plan['kernel']) or not kernel.KERNEL.fullmatch(plan['old_kernel'])
            or not re.fullmatch(r'[a-f0-9]{32}', plan['machine_id'])):
        refuse('candidate_binding_changed')
    receipt_sha = rpm.sha(rpm.read(Path(candidate_stage) / 'kernel-installed.json', rpm.MAX_XML))
    return Path(candidate_stage), plan, plan_sha, installed, receipt_sha


def _context(stage, *, finalized=False):
    stage = Path(stage)
    if (stage.is_symlink() or not stage.is_absolute() or not stage.is_dir()
            or stage.parent.name != 'os-updates' or stage.resolve() != stage):
        refuse('unowned_stage')
    manager = stage.parent.parent
    transaction = _read_json(manager / 'os-transaction.json')
    latest = _read_json(manager / 'os-latest.json')
    marker_path = manager / 'maintenance.json'
    marker = _read_json(marker_path) if os.path.lexists(marker_path) else None
    completed = finalized and transaction.get('state') == 'complete' and transaction.get('finalization') == 'complete'
    if (transaction.get('stage') != str(stage) or latest.get('stage') != str(stage)
            or transaction.get('state') not in {'reboot_preparing', 'reboot_requested', 'recovery_required', 'postcheck', 'complete'}
            or (marker is None and not completed)
            or (marker is not None and (marker.get('active') is not True or marker.get('release') != str(stage)))):
        refuse('operation_or_maintenance_not_owned')
    try:
        original = transaction['boot_id']
        if str(uuid.UUID(original)) != original or latest.get('boot_id') != original:
            raise ValueError()
    except (KeyError, ValueError, TypeError, AttributeError):
        refuse('operation_boot_binding_changed')
    return transaction


def _operation_sha(stage):
    return rpm.sha(rpm.read(Path(stage) / 'operation.json', 8192))


def _proof(stage, *, runner):
    candidate_stage, candidate, sha, installed, receipt_sha = _candidate(stage)
    kernel.verify_payload(candidate, runner=runner)
    if kernel.generated_snapshot(candidate, runner=runner) != installed['generated']:
        refuse('candidate_artifacts_changed')
    if rpm.inventory(runner)[2] != candidate['after_inventory']:
        refuse('package_inventory_changed')
    return candidate_stage, candidate, sha, installed, receipt_sha


def _current(stage):
    path = Path(stage) / 'kernel-boot-current.json'
    if not os.path.lexists(path):
        return None
    pointer = _read_json(path)
    exact(pointer, {'id', 'sha256'})
    if not re.fullmatch(r'[a-f0-9]{32}', str(pointer['id'])):
        refuse('invalid_transition_pointer')
    plan_path = Path(stage) / ('kernel-boot-' + pointer['id'] + '-plan.json')
    raw = rpm.read(plan_path, rpm.MAX_XML)
    if rpm.sha(raw) != pointer['sha256'] or strict_json(raw).get('id') != pointer['id']:
        refuse('transition_pointer_changed')
    return plan_path, strict_json(raw)


def _result_path(stage, plan):
    return Path(stage) / ('kernel-boot-' + plan['id'] + '-result.json')


def _accepted(stage, plan):
    result = _read_json(_result_path(stage, plan))
    checksum = rpm.sha(kernel.encode(plan))
    expected = _result_fields(plan)
    if ({key: value for key, value in result.items() if key != 'aide'} != expected
            or result.get('aide', {}).get('ok') is not True
            or result.get('aide', {}).get('plan_sha256') != checksum):
        refuse('prior_transition_not_accepted')
    return result


def _result_fields(plan):
    return {'schema': 1, 'transition_sha256': rpm.sha(kernel.encode(plan)), 'phase': plan['phase'],
            'boot_id': plan['boot_id'], 'kernel': plan['kernel'], 'old_kernel': plan['old_kernel'],
            'operation_sha256': plan['operation_sha256'], 'candidate_plan_sha256': plan['candidate_plan_sha256'],
            'installed_sha256': plan['installed_sha256'],
            'outcome': 'candidate' if plan['running_kernel'] == plan['kernel'] else 'recovery',
            'release_accepted': False}


def _previous(stage, plan):
    pointer = plan['previous']
    exact(pointer, {'id', 'sha256'})
    if not re.fullmatch(r'[a-f0-9]{32}', str(pointer['id'])):
        refuse('invalid_predecessor_identity')
    raw = rpm.read(Path(stage) / ('kernel-boot-' + pointer['id'] + '-plan.json'), rpm.MAX_XML)
    previous = strict_json(raw)
    if rpm.sha(raw) != pointer['sha256'] or previous.get('id') != pointer['id']:
        refuse('predecessor_binding_changed')
    _prior_evidence(stage, previous, allow_intent=plan['phase'] in {'postboot', 'resume'})
    return previous


def _prior_evidence(stage, plan, *, allow_intent=False):
    if os.path.lexists(_result_path(stage, plan)):
        return _accepted(stage, plan)
    if not allow_intent or plan.get('phase') not in {'arm', 'commit', 'resume'}:
        refuse('prior_transition_not_accepted')
    checksum = rpm.sha(kernel.encode(plan))
    intent_path = Path(stage) / ('kernel-boot-' + plan['id'] + '-intent.json')
    if plan['phase'] == 'resume' and not os.path.lexists(intent_path):
        # Resume only observes GRUB's new-boot changes; it never writes ENV.
        # An interruption before its intent therefore cannot have initiated
        # its AIDE acceptance. Retain this exact observed plan in the chain,
        # without asserting its historical acceptance or preparation occurred.
        return {**_result_fields(plan), 'accepted': False, 'unexecuted': True}
    intent = _read_json(intent_path)
    exact(intent, {'schema', 'plan_sha256', 'prepared'})
    if (type(intent['schema']) is not int or intent['schema'] != 1 or intent['plan_sha256'] != checksum
            or intent['prepared'].get('ok') is not True or intent['prepared'].get('plan_sha256') != checksum):
        refuse('interrupted_promotion_intent_changed')
    return {**_result_fields(plan), 'accepted': False}


def _check_health(health, stage, boot, candidate):
    if (not isinstance(health, dict) or health.get('ok') is not True or health.get('stage') != str(stage)
            or health.get('boot_id') != boot or health.get('kernel') != candidate
            or any(health.get('checks', {}).get(name) is not True for name in REQUIRED_CHECKS)):
        refuse('operation_bound_runtime_acceptance_required')


def _raw(value):
    try:
        raw = base64.b64decode(value, validate=True)
    except (ValueError, TypeError):
        refuse('invalid_environment_encoding')
    parse_environment(raw)
    return raw


def _changed_description(before, raw):
    return {**before, 'sha256': rpm.sha(raw), 'bytes': len(raw)}


def _render(stage, token, before, expected, *, runner):
    if not kernel.SHA.fullmatch(TOOL_SHA256) or rpm.sha(rpm.read(TOOL)) != TOOL_SHA256:
        refuse('environment_tool_not_qualified')
    path = Path(stage) / ('kernel-boot-' + token + '-render.env')
    rpm.immutable(path, before)
    variables = parse_environment(before)
    removed = sorted(set(variables) - set(expected))
    changed = [key + '=' + expected[key] for key in sorted(expected) if variables.get(key) != expected[key]]
    if removed:
        runner([TOOL, str(path), 'unset', *removed], timeout=120)
    if changed:
        runner([TOOL, str(path), 'set', *changed], timeout=120)
    result = rpm.read(path, 1024)
    if parse_environment(result) != expected:
        refuse('rendered_environment_changed')
    return result


def _replace(before, after, expected):
    """Atomic same-directory replacement; no torn live GRUB environment block."""
    path = Path(ENV)
    if rpm.read(path, 1024) != before or kernel.describe(path) != expected:
        refuse('environment_changed_before_write')
    attrs = {key: os.getxattr(path, key, follow_symlinks=False) for key in os.listxattr(path, follow_symlinks=False)}
    fd, name = tempfile.mkstemp(prefix='.captains-log-grubenv-', dir=path.parent)
    temporary = Path(name)
    try:
        with os.fdopen(fd, 'wb') as out:
            os.fchown(out.fileno(), expected['uid'], expected['gid'])
            os.fchmod(out.fileno(), expected['mode'])
            out.write(after)
            out.flush()
            for key, value in attrs.items():
                os.setxattr(temporary, key, value, follow_symlinks=False)
            os.fsync(out.fileno())
        if rpm.read(path, 1024) != before or kernel.describe(path) != expected:
            refuse('environment_changed_before_replace')
        if kernel.describe(temporary) != _changed_description(expected, after):
            refuse('replacement_metadata_changed')
        os.replace(temporary, path)
        parent = os.open(path.parent, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW)
        try:
            os.fsync(parent)
        finally:
            os.close(parent)
    finally:
        if temporary.exists():
            temporary.unlink()
    if rpm.read(path, 1024) != after or kernel.describe(path) != _changed_description(expected, after):
        refuse('environment_replacement_not_verified')


def _new_plan(stage, phase, *, runner, health=None):
    _context(stage)
    candidate_stage, candidate, candidate_sha, installed, installed_sha = _proof(stage, runner=runner)
    boot, running = boot_id(), runner(['/usr/bin/uname', '-r'])
    old_entry = candidate['machine_id'] + '-' + candidate['old_kernel']
    candidate_entry = candidate['machine_id'] + '-' + candidate['kernel']
    current = _current(stage)
    prior = None
    if phase == 'arm':
        if current is not None or running != candidate['old_kernel']:
            refuse('arm_requires_unarmed_recovery_kernel')
        before = rpm.read(ENV, 1024)
        description = kernel.describe(ENV)
        if description != installed['mutable'][ENV]:
            refuse('installed_environment_changed')
    else:
        if current is None:
            refuse('owned_arm_required')
        prior_path, prior = current
        accepted = _prior_evidence(stage, prior, allow_intent=phase in {'postboot', 'resume'})
        expected_prior = {'postboot'} if phase == 'commit' else {'commit', 'resume'} if phase == 'resume' else {'arm'}
        if prior['phase'] not in expected_prior:
            refuse('unexpected_prior_transition')
        if phase in {'abort', 'commit'} and boot != prior['boot_id']:
            refuse('same_boot_transition_required')
        if phase in {'postboot', 'resume'} and boot == prior['boot_id']:
            refuse('new_boot_required')
        if phase in {'commit', 'resume'} and (accepted['outcome'] != 'candidate' or running != candidate['kernel']):
            refuse('verified_candidate_boot_required')
        if running not in (candidate['old_kernel'], candidate['kernel']):
            refuse('unexpected_running_kernel')
        before = _raw(prior['after_raw'])
        description = prior['files'][0]['after']
        if phase not in {'postboot', 'resume'} and (rpm.read(ENV, 1024) != before or kernel.describe(ENV) != description):
            refuse('prior_environment_changed')
    default = candidate['kernel'] if phase == 'resume' else candidate['old_kernel']
    if runner(['/usr/sbin/grubby', '--default-kernel']) != '/boot/vmlinuz-' + default:
        refuse('persistent_recovery_default_changed')
    token = uuid.uuid4().hex
    variables = parse_environment(before)
    observed_raw = rpm.read(ENV, 1024)
    expected = transition_variables(variables, phase, old_entry, candidate_entry,
                                    observed=parse_environment(observed_raw) if phase in {'postboot', 'resume'} else None,
                                    restored=parse_environment(_raw(prior['before_raw'])) if phase == 'abort' else None)
    # An abort restores the exact installed bytes, including empty-vs-absent
    # next_entry and original serialization, so a later deferred window can
    # safely re-arm against the original immutable install receipt.
    after = (observed_raw if phase in {'postboot', 'resume'} else _raw(prior['before_raw']) if phase == 'abort'
             else _render(stage, token, before, expected, runner=runner))
    if phase in {'postboot', 'resume'}:
        if running == candidate['kernel']:
            kernel.verify_postboot(candidate_stage, runner=runner)
        elif kernel.security.status(runner).get('host_controls_ok') is not True:
            refuse('recovery_host_security_failed')
        if kernel.describe(ENV) != _changed_description(description, after):
            refuse('postboot_environment_metadata_changed')
    if phase == 'commit':
        _check_health(health, stage, boot, candidate['kernel'])
    transition = {'schema': 1, 'kind': 'kernel-boot-v1', 'id': token, 'phase': phase,
                  'sequence': prior['sequence'] + 1 if phase == 'resume' else PHASES[phase],
                  'stage': str(stage), 'operation_sha256': _operation_sha(stage),
                  'boot_id': boot, 'running_kernel': running,
                  'candidate_stage': str(candidate_stage), 'candidate_plan_sha256': candidate_sha,
                  'installed_sha256': installed_sha, 'kernel': candidate['kernel'], 'old_kernel': candidate['old_kernel'],
                  'candidate_entry': candidate_entry, 'old_entry': old_entry,
                  'previous': None if prior is None else {'id': prior['id'], 'sha256': rpm.sha(kernel.encode(prior))},
                  'before_raw': base64.b64encode(before).decode(), 'after_raw': base64.b64encode(after).decode(),
                  'files': [{'path': ENV, 'before': description, 'after': _changed_description(description, after)}],
                  'health': health if phase == 'commit' else None}
    transition['manifest_sha256'] = digest(transition)
    path = Path(stage) / ('kernel-boot-' + token + '-plan.json')
    kernel.record(stage, path.name, transition)
    atomic_json(Path(stage) / 'kernel-boot-current.json', {'id': token, 'sha256': rpm.sha(kernel.encode(transition))})
    return path, transition


def _execute(stage, phase, *, prepare, accept, runner, health=None):
    require_linux_root()
    stage = Path(stage)
    current = _current(stage)
    reuse = (current is not None and current[1]['phase'] == phase
             and (phase != 'resume' or current[1]['boot_id'] == boot_id()))
    path, plan = current if reuse else _new_plan(stage, phase, runner=runner, health=health)
    validate_transition(stage, path, runner=runner)
    _proof(stage, runner=runner)
    intent = stage / ('kernel-boot-' + plan['id'] + '-intent.json')
    checksum = rpm.sha(kernel.encode(plan))
    if not os.path.lexists(intent):
        prepared = prepare(stage, path)
        if prepared.get('ok') is not True or prepared.get('plan_sha256') != checksum:
            refuse('integrity_preparation_not_bound')
        kernel.record(stage, intent.name, {'schema': 1, 'plan_sha256': checksum, 'prepared': prepared})
    else:
        retained = _read_json(intent)
        if (retained.get('plan_sha256') != checksum or retained.get('prepared', {}).get('ok') is not True
                or retained.get('prepared', {}).get('plan_sha256') != checksum):
            refuse('transition_intent_changed')
    before, after = _raw(plan['before_raw']), _raw(plan['after_raw'])
    actual = rpm.read(ENV, 1024)
    if phase not in {'postboot', 'resume'} and actual == before:
        _replace(before, after, plan['files'][0]['before'])
    elif actual != after:
        refuse('transition_environment_changed')
    if kernel.describe(ENV) != plan['files'][0]['after']:
        refuse('transition_metadata_changed')
    accepted = accept(stage, path)
    if accepted.get('ok') is not True or accepted.get('plan_sha256') != checksum:
        refuse('integrity_acceptance_not_bound')
    result = {**_result_fields(plan), 'aide': accepted}
    result_path = _result_path(stage, plan)
    if os.path.lexists(result_path):
        # AIDE idempotent acceptance may report baseline_changed=false on retry.
        existing = _accepted(stage, plan)
        if {k: v for k, v in existing.items() if k != 'aide'} != {k: v for k, v in result.items() if k != 'aide'}:
            refuse('transition_result_changed')
        return existing
    kernel.record(stage, result_path.name, result)
    return result


def arm_candidate(stage, *, prepare, accept, runner=run):
    return _execute(stage, 'arm', prepare=prepare, accept=accept, runner=runner)


def abort_candidate(stage, *, prepare, accept, runner=run):
    # A failed AIDE acceptance may leave an owned arm intent and exact armed
    # bytes. Complete that same-boot chain entry before creating its inverse.
    current = _current(stage)
    if current is None:
        return {'ok': True, 'phase': 'unarmed', 'release_accepted': False}
    if current is not None and current[1]['phase'] == 'arm' and not _result_path(stage, current[1]).exists():
        _execute(stage, 'arm', prepare=prepare, accept=accept, runner=runner)
    return _execute(stage, 'abort', prepare=prepare, accept=accept, runner=runner)


def verify_postboot(stage, *, prepare, accept, runner=run):
    current = _current(stage)
    if current is not None and current[1]['phase'] in {'commit', 'resume'} and current[1]['boot_id'] != boot_id():
        return resume_candidate(stage, prepare=prepare, accept=accept, runner=runner)
    if current is not None and current[1]['phase'] == 'resume':
        return _execute(stage, 'resume', prepare=prepare, accept=accept, runner=runner)
    if current is not None and current[1]['phase'] == 'commit':
        # Promotion may have changed saved_entry before its AIDE callback or
        # maintenance finalization failed. Reuse its accepted postboot proof;
        # commit_candidate resumes the exact promotion intent separately.
        path, plan = current
        validate_transition(stage, path, runner=runner)
        previous = _previous(stage, plan)
        _verify_actual(plan)
        return _accepted(stage, previous)
    return _execute(stage, 'postboot', prepare=prepare, accept=accept, runner=runner)


def commit_candidate(stage, *, health, prepare, accept, runner=run):
    _, candidate, _, _, _ = _candidate(stage)
    _check_health(health, stage, boot_id(), candidate['kernel'])
    current = _current(stage)
    if current is not None and current[1]['phase'] == 'resume':
        validate_transition(stage, current[0], runner=runner)
        _verify_actual(current[1])
        return _accepted(stage, current[1])
    return _execute(stage, 'commit', health=health, prepare=prepare, accept=accept, runner=runner)


def resume_candidate(stage, *, prepare, accept, runner=run):
    """Reconcile a later candidate boot after an already accepted promotion.

    This is boot/AIDE evidence only. Fresh full runtime health must precede
    commit_candidate and the lifecycle's new final acceptance receipt.
    """
    return _execute(stage, 'resume', prepare=prepare, accept=accept, runner=runner)


def _verify_actual(plan):
    current = kernel.describe(ENV)
    if current not in (plan['files'][0]['before'], plan['files'][0]['after']):
        refuse('current_transition_environment_changed')
    if os.path.lexists(_result_path(plan['stage'], plan)) and current != plan['files'][0]['after']:
        refuse('accepted_transition_environment_reverted')


def candidate_status(stage, *, runner=run):
    """Inspect owned progress without arming or accepting a new transition."""
    current = _current(stage)
    if current is None:
        return {'phase': None, 'accepted': False, 'outcome': None, 'release_accepted': False}
    path, plan = current
    if plan['phase'] in {'arm', 'commit', 'resume'} and plan['boot_id'] != boot_id():
        transaction = _context(stage)
        candidate_stage, candidate, checksum, installed, installed_sha = _candidate(stage)
        _validate_plan(Path(stage), plan, candidate_stage, candidate, checksum, installed, installed_sha, transaction)
        evidence = _prior_evidence(stage, plan, allow_intent=True)
        # Only postboot processing may authorize observed bootloader changes.
        return {'phase': plan['phase'], 'accepted': evidence.get('accepted', True), 'outcome': None, 'release_accepted': False}
    validate_transition(stage, path, runner=runner, finalized=True)
    _verify_actual(plan)
    accepted = os.path.lexists(_result_path(stage, plan))
    result = _accepted(stage, plan) if accepted else None
    outcome = result['outcome'] if result is not None and plan['phase'] in {'postboot', 'commit', 'resume'} else None
    if plan['phase'] == 'commit' and not accepted:
        outcome = _accepted(stage, _previous(stage, plan))['outcome']
    return {'phase': plan['phase'], 'accepted': accepted, 'outcome': outcome, 'release_accepted': False}


def verified_abort(stage, *, runner=run):
    current = _current(stage)
    if current is None or current[1]['phase'] != 'abort':
        refuse('accepted_abort_required')
    path, plan = current
    validate_transition(stage, path, runner=runner, finalized=True)
    _accepted(stage, plan)
    _verify_actual(plan)
    return {'mutable': {ENV: plan['files'][0]['after']},
            'receipt_sha256': rpm.sha(rpm.read(_result_path(stage, plan), rpm.MAX_XML)),
            'operation_sha256': plan['operation_sha256'], 'kernel_plan_sha256': plan['candidate_plan_sha256'],
            'installed_sha256': plan['installed_sha256'], 'kernel': plan['kernel'],
            'recovery_kernel': plan['old_kernel'], 'boot_id': plan['boot_id']}


def validate_transition(stage, path, *, runner=run, finalized=False):
    stage, path = Path(stage), Path(path)
    transaction = _context(stage, finalized=finalized)
    current = _current(stage)
    if current is None or current[0] != path or path.parent != stage or not NAME.fullmatch(path.name):
        refuse('unowned_transition_plan')
    plan = current[1]
    candidate_stage, candidate, candidate_sha, installed, installed_sha = _candidate(stage)
    _validate_plan(stage, plan, candidate_stage, candidate, candidate_sha, installed, installed_sha, transaction)
    if plan['boot_id'] != boot_id() or plan['running_kernel'] != runner(['/usr/bin/uname', '-r']):
        refuse('transition_current_boot_changed')
    expected_default = '/boot/vmlinuz-' + (candidate['kernel'] if plan['phase'] == 'resume' or plan['phase'] == 'commit'
                       and rpm.read(ENV, 1024) == _raw(plan['after_raw']) else candidate['old_kernel'])
    if runner(['/usr/sbin/grubby', '--default-kernel']) != expected_default:
        refuse('transition_default_changed')
    return plan, rpm.sha(kernel.encode(plan))


def _validate_plan(stage, plan, candidate_stage, candidate, candidate_sha, installed, installed_sha, transaction, seen=None):
    exact(plan, PLAN_FIELDS)
    seen = set() if seen is None else seen
    if plan['id'] in seen or len(seen) >= 64:
        refuse('transition_chain_limit')
    seen.add(plan['id'])
    if (type(plan['schema']) is not int or plan['schema'] != 1 or plan['kind'] != 'kernel-boot-v1'
            or plan['phase'] not in PHASES or type(plan['sequence']) is not int
            or not re.fullmatch(r'[a-f0-9]{32}', str(plan['id']))
            or plan.get('stage') != str(stage)
            or plan.get('operation_sha256') != _operation_sha(stage)
            or plan.get('candidate_stage') != str(candidate_stage) or plan.get('candidate_plan_sha256') != candidate_sha
            or plan.get('installed_sha256') != installed_sha or plan.get('kernel') != candidate['kernel']
            or plan.get('old_kernel') != candidate['old_kernel']
            or (plan['phase'] != 'resume' and plan.get('sequence') != PHASES[plan['phase']])
            or plan['running_kernel'] not in (candidate['old_kernel'], candidate['kernel'])
            or plan.get('manifest_sha256') != digest({key: value for key, value in plan.items() if key != 'manifest_sha256'})):
        refuse('transition_binding_changed')
    try:
        if str(uuid.UUID(plan['boot_id'])) != plan['boot_id']:
            raise ValueError()
    except (ValueError, TypeError, AttributeError):
        refuse('transition_boot_identity_invalid')
    before, after = _raw(plan['before_raw']), _raw(plan['after_raw'])
    if plan['old_entry'] != candidate['machine_id'] + '-' + candidate['old_kernel'] or plan['candidate_entry'] != candidate['machine_id'] + '-' + candidate['kernel']:
        refuse('boot_entry_binding_changed')
    predecessor = _previous(stage, plan) if plan['phase'] != 'arm' else None
    expected = transition_variables(parse_environment(before), plan['phase'], plan['old_entry'], plan['candidate_entry'],
                                    observed=parse_environment(after) if plan['phase'] in {'postboot', 'resume'} else None,
                                    restored=parse_environment(_raw(predecessor['before_raw'])) if plan['phase'] == 'abort' else None)
    if parse_environment(after) != expected or len(plan.get('files', [])) != 1:
        refuse('transition_semantics_changed')
    item = plan['files'][0]
    exact(item, {'path', 'before', 'after'})
    exact(item['before'], {'sha256', 'bytes', 'kind', 'uid', 'gid', 'mode', 'xattrs_sha256'})
    if (item.get('path') != ENV or item['before'].get('sha256') != rpm.sha(before)
            or item['before'].get('bytes') != 1024 or item['before'].get('kind') != 'file'
            or item['before'].get('uid') != 0 or item['before'].get('gid') != 0 or item['before'].get('mode') != 0o600
            or not kernel.SHA.fullmatch(str(item['before'].get('xattrs_sha256')))
            or item.get('after') != _changed_description(item['before'], after)):
        refuse('transition_file_binding_changed')
    if plan['phase'] == 'arm':
        if (plan['previous'] is not None or item['before'] != installed['mutable'][ENV]
                or plan['boot_id'] != transaction['boot_id'] or plan['running_kernel'] != candidate['old_kernel']):
            refuse('arm_origin_changed')
    else:
        previous = predecessor
        wanted = {'postboot'} if plan['phase'] == 'commit' else {'commit', 'resume'} if plan['phase'] == 'resume' else {'arm'}
        if (previous.get('phase') not in wanted
                or plan['phase'] == 'resume' and plan['sequence'] != previous['sequence'] + 1):
            refuse('invalid_predecessor_phase')
        # Recursion strictly decreases through commit -> postboot -> arm.
        _validate_plan(stage, previous, candidate_stage, candidate, candidate_sha, installed, installed_sha, transaction, seen)
        if plan['before_raw'] != previous['after_raw'] or item['before'] != previous['files'][0]['after']:
            refuse('predecessor_environment_changed')
        if plan['phase'] == 'abort' and (plan['after_raw'] != previous['before_raw'] or item['after'] != previous['files'][0]['before']):
            refuse('abort_original_bytes_changed')
        same_boot = plan['boot_id'] == previous['boot_id']
        if (same_boot != (plan['phase'] in {'abort', 'commit'})
                or plan['phase'] == 'abort' and plan['running_kernel'] != candidate['old_kernel']
                or plan['phase'] in {'commit', 'resume'} and (plan['running_kernel'] != candidate['kernel']
                                                or previous['running_kernel'] != candidate['kernel'])):
            refuse('predecessor_boot_binding_changed')
    if plan['phase'] == 'commit':
        _check_health(plan['health'], stage, plan['boot_id'], candidate['kernel'])
    elif plan['health'] is not None:
        refuse('unexpected_health_receipt')


def accepted_transitions(stage, *, runner=run):
    """Return the exact postboot/promotion receipt digests for final acceptance.

    postboot_sha256 hashes the original accepted postboot result;
    promotion_sha256 always hashes the immutable original commit PLAN. That
    plan is proven either by its accepted result or by its exact prepared
    intent followed by an accepted resume, without inventing old acceptance.
    resume_sha256 hashes the latest accepted resume result, or is null on the
    first boot. boot_id identifies the currently verified boot.
    The caller must still validate runtime health and maintenance finalization.
    Candidate resolution may use the owner's immutable completion record after
    the pending pointer has been cleared; it must never search for another VM.
    """
    current = _current(stage)
    if current is None or current[1]['phase'] not in {'commit', 'resume'}:
        refuse('accepted_promotion_required')
    path, plan = current
    validate_transition(stage, path, runner=runner, finalized=True)
    _accepted(stage, plan)
    _verify_actual(plan)
    promotion = plan
    while promotion['phase'] == 'resume':
        promotion = _previous(stage, promotion)
    previous = _previous(stage, promotion)
    if previous['phase'] != 'postboot' or previous['running_kernel'] != plan['kernel']:
        refuse('accepted_candidate_postboot_required')
    return {'postboot_sha256': rpm.sha(rpm.read(_result_path(stage, previous), rpm.MAX_XML)),
            'promotion_sha256': rpm.sha(kernel.encode(promotion)),
            'resume_sha256': rpm.sha(rpm.read(_result_path(stage, plan), rpm.MAX_XML)) if plan['phase'] == 'resume' else None,
            'operation_sha256': plan['operation_sha256'], 'kernel_plan_sha256': plan['candidate_plan_sha256'],
            'installed_sha256': plan['installed_sha256'], 'kernel': plan['kernel'],
            'boot_id': plan['boot_id'], 'recovery_kernel': plan['old_kernel']}


def resume_predecessor(stage, path, *, runner=run):
    """Give AIDE the narrowly validated old promotion for journal recovery.

    The old plan retains its original boot identity. An interrupted promotion
    is accepted only as an exact durable intent referencing its preparation;
    this function does not declare its historical AIDE acceptance successful.
    """
    plan, _ = validate_transition(stage, path, runner=runner)
    if plan['phase'] != 'resume':
        refuse('resume_transition_required')
    _verify_actual(plan)
    predecessor = _previous(stage, plan)
    while predecessor['phase'] == 'resume':
        predecessor = _previous(stage, predecessor)
    if predecessor['phase'] != 'commit':
        refuse('promotion_predecessor_required')
    return predecessor, rpm.sha(kernel.encode(predecessor))


def integrity_predecessor(stage, path, *, runner=None):
    """Exact immediate old-boot phase for AIDE's historical pending CAS.

    Only a consumed arm or a promoted candidate's later boot can supersede an
    interrupted AIDE transition. The database owner must match that precise
    preparation and retained input/output evidence before resolving its journal.
    """
    plan, _ = validate_transition(stage, path, runner=run if runner is None else runner)
    if plan['phase'] not in {'postboot', 'resume'}:
        refuse('boot_reconciliation_required')
    _verify_actual(plan)
    predecessor = _previous(stage, plan)
    while (predecessor['phase'] == 'resume'
           and not os.path.lexists(_result_path(stage, predecessor))
           and not os.path.lexists(Path(stage) / ('kernel-boot-' + predecessor['id'] + '-intent.json'))):
        predecessor = _previous(stage, predecessor)
    allowed = {'arm'} if plan['phase'] == 'postboot' else {'commit', 'resume'}
    if predecessor['phase'] not in allowed or predecessor['boot_id'] == plan['boot_id']:
        refuse('integrity_predecessor_changed')
    return predecessor, rpm.sha(kernel.encode(predecessor))


def bound_integrity_plan(manager, stage, path, *, preparing):
    identity = manager.guard()
    stage = Path(stage)
    if stage.parent != identity.root / 'manager/os-updates':
        refuse('unenrolled_transition_stage')
    return validate_transition(stage, path, runner=run)


def integrity_snapshot(manager, plan, phase, retained=None):
    from . import aide_updates
    if phase not in {'prepare', 'forward'}:
        refuse('use_separate_abort_transition')
    item = plan['files'][0]
    target = 'after' if phase == 'forward' or plan['phase'] in {'postboot', 'resume'} else 'before'
    description, metadata = aide_updates._measure(manager, {'path': ENV})
    expected = {key: value for key, value in item[target].items() if key != 'xattrs_sha256'}
    if description != expected or metadata['xattrs_sha256'] != item[target]['xattrs_sha256']:
        refuse('integrity_snapshot_changed')
    result = {ENV: metadata}
    if retained is not None and retained != result:
        refuse('integrity_metadata_changed')
    return result


def allowed_integrity_report(report, plan, phase):
    if phase not in {'prepare', 'forward'}:
        refuse('use_separate_abort_transition')
    permitted = {ENV} if phase == 'forward' or plan['phase'] in {'postboot', 'resume'} else set()
    if report.get('added') or report.get('removed') or set(report.get('changed', {})) - permitted:
        refuse('unrelated_integrity_change')
