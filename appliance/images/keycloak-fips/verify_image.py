#!/usr/bin/env python3
"""Inspect a candidate and its real non-FIPS refusal without starting services."""
import argparse
import datetime
import json
from pathlib import Path
import struct
import subprocess
import tempfile
import zipfile


def run(args):
    return subprocess.run(args, capture_output=True, text=True, timeout=180)


def verify_recorded_strict_mode(bytecode):
    """Check the pinned release's actual crypto-provider startup instructions.

    Keycloak 26.8.1 records the enum in generated bytecode but does not retain
    kc.fips-mode in keycloak-persisted.properties. Constant text alone is not
    evidence: require the exact method invoking setCryptoProvider(STRICT)
    and configureTruststore(STRICT), as recorded by initCrypto in this release.
    A changed Quarkus recorder layout intentionally requires a fresh review.
    """
    position = 0

    def take(size):
        nonlocal position
        value = bytecode[position:position + size]
        assert len(value) == size, "truncated class"
        position += size
        return value

    def u2():
        return struct.unpack(">H", take(2))[0]

    def u4():
        return struct.unpack(">I", take(4))[0]

    assert u4() == 0xCAFEBABE
    take(4)  # minor/major class version
    pool = [None]
    count = u2()
    while len(pool) < count:
        tag = take(1)[0]
        if tag == 1:
            value = take(u2()).decode()
        elif tag in (7, 8, 16, 19, 20):
            value = u2()
        elif tag in (9, 10, 11, 12, 17, 18):
            value = (u2(), u2())
        elif tag in (3, 4):
            value = take(4)
        elif tag in (5, 6):
            value = take(8)
        elif tag == 15:
            value = (take(1)[0], u2())
        else:
            raise AssertionError(f"unsupported constant tag {tag}")
        pool.append((tag, value))
        if tag in (5, 6):
            pool.append(None)

    def resolve(index):
        tag, value = pool[index]
        if tag in (7, 8):
            return resolve(value)
        if tag in (9, 10, 11, 12):
            return tuple(resolve(item) for item in value)
        return value

    def index_of(tag, value):
        matches = [i for i, item in enumerate(pool) if item and item[0] == tag and resolve(i) == value]
        assert len(matches) == 1, f"expected one constant {value}"
        return matches[0]

    recorder = "org/keycloak/quarkus/runtime/KeycloakRecorder"
    fips = "org/keycloak/common/crypto/FipsMode"
    strict = index_of(8, "STRICT")
    assert strict < 256
    packed = lambda index: struct.pack(">H", index)
    expected = (
        b"\xbb" + packed(index_of(7, recorder)) + b"\x59\xb7" +
        packed(index_of(10, (recorder, ("<init>", "()V")))) + b"\x4e\x12" + bytes([strict]) +
        b"\xb8" + packed(index_of(10, (fips, ("valueOf", f"(Ljava/lang/String;)L{fips};")))) +
        b"\x3a\x04\x2d\x19\x04\xb6" +
        packed(index_of(10, (recorder, ("setCryptoProvider", f"(L{fips};)V")))) +
        b"\x12" + bytes([strict]) +
        b"\xb8" + packed(index_of(10, (fips, ("valueOf", f"(Ljava/lang/String;)L{fips};")))) +
        b"\x3a\x05\x2d\x19\x05\xb6" +
        packed(index_of(10, (recorder, ("configureTruststore", f"(L{fips};)V")))) + b"\xb1"
    )
    take(6)  # flags, this class, superclass
    take(2 * u2())  # interfaces
    assert u2() == 0, "unexpected recorder fields"
    matched = False
    for _ in range(u2()):
        take(2)  # method flags
        method_name, descriptor = resolve(u2()), resolve(u2())
        for _ in range(u2()):
            name = resolve(u2())
            attribute = take(u4())
            if name == "Code" and method_name == "deploy_0":
                assert descriptor == "(Lio/quarkus/runtime/StartupContext;[Ljava/lang/Object;)V"
                length = struct.unpack_from(">I", attribute, 4)[0]
                assert attribute[8:8 + length] == expected, "crypto provider/truststore recorder does not set STRICT"
                matched = True
    assert matched, "missing crypto startup method"


def main():
    if not __debug__:
        raise RuntimeError("Run this verification without Python optimization; assertions are required")
    parser = argparse.ArgumentParser()
    parser.add_argument("--image", required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    inspected = run(["docker", "image", "inspect", args.image])
    inspected.check_returncode()
    image = json.loads(inspected.stdout)[0]
    assert image["Architecture"] == "amd64"
    assert image["Config"]["User"] == "1000:1000"
    base = ["docker", "run", "--rm", "--platform", "linux/amd64", "--network", "none", "--read-only", "--cap-drop", "ALL", "--security-opt", "no-new-privileges", "--tmpfs", "/tmp:rw,noexec,nosuid,nodev,size=64m"]
    version = run(base + [args.image, "--version"])
    version.check_returncode()
    assert "26.8.1" in version.stdout + version.stderr
    settings = run(base + [args.image, "show-config"])
    settings.check_returncode()
    combined = settings.stdout + settings.stderr
    for marker in ("fips", "recovery-codes", "passkeys", "postgres"):
        assert marker in combined, marker
    # Inspect the optimized artifact, not merely caller-supplied environment.
    created = run(["docker", "create", "--platform", "linux/amd64", args.image])
    created.check_returncode()
    container_id = created.stdout.strip()
    try:
        with tempfile.TemporaryDirectory(prefix="nebulalog-keycloak-artifact-") as directory:
            archive = Path(directory) / "generated-bytecode.jar"
            copied = run(["docker", "cp", container_id + ":/opt/keycloak/lib/quarkus/generated-bytecode.jar", str(archive)])
            copied.check_returncode()
            with zipfile.ZipFile(archive) as jar:
                persisted = jar.read("META-INF/keycloak-persisted.properties").decode()
                recorders = [name for name in jar.namelist() if name.startswith("io/quarkus/runner/recorded/KeycloakProcessor$initCrypto") and name.endswith(".class")]
                assert len(recorders) == 1
                verify_recorded_strict_mode(jar.read(recorders[0]))
            for setting in ("kc.features=fips,recovery-codes,passkeys", "kc.db=postgres", "kc.optimized=true"):
                assert setting in persisted.splitlines(), setting
    finally:
        removed = run(["docker", "rm", container_id])
        removed.check_returncode()
    checksum = run(base + ["--entrypoint", "/bin/bash", args.image, "-c", "cd /opt/keycloak/providers && sha256sum -c /opt/nebulalog/bc-fips.sha256"])
    checksum.check_returncode()
    kernel = run(base + ["--entrypoint", "/bin/bash", args.image, "-c", "if [[ -r /proc/sys/crypto/fips_enabled ]]; then cat /proc/sys/crypto/fips_enabled; else printf 'unavailable'; fi"])
    kernel.check_returncode()
    # Starting a real FIPS host requires enrollment, so do not attempt it here.
    refusal = "not_run_on_fips_host"
    if kernel.stdout.strip() != "1":
        started = run(base + [args.image, "start", "--optimized"])
        assert started.returncode == 78, started.returncode
        assert "actual FIPS-enabled host kernel is required" in started.stderr
        refusal = "passed_non_fips_kernel_refused"
    record = {
        "checked_at": datetime.datetime.now(datetime.timezone.utc).isoformat(),
        "image_id": image["Id"],
        "repo_digests": image.get("RepoDigests", []),
        "platform": "linux/amd64",
        "user": image["Config"]["User"],
        "version": (version.stdout + version.stderr).strip(),
        "provider_sha256": "passed_all_four_original_jars",
        "configured_features": "fips,recovery-codes,passkeys",
        "configured_fips_mode": "strict",
        "optimized_artifact_fips_mode": "strict",
        "optimized_artifact_evidence": "generated startup method invokes setCryptoProvider(FipsMode.STRICT) and configureTruststore(FipsMode.STRICT)",
        "host_kernel_fips": kernel.stdout.strip(),
        "start_gate": refusal,
        "guest_startup": "not_tested",
        "authentication": "not_tested",
        "fips_qualification": "not_established"
    }
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(record, indent=2) + "\n")
    print(json.dumps(record, indent=2))


if __name__ == "__main__":
    main()
