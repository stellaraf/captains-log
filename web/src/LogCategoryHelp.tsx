export function LogCategoryScope({ type }: { type: string }) {
  if (type === "tunnel")
    return (
      <div className="notice warning">
        Tunnel Inspection parsing is not available in this development build.
        Forwarded messages are retained in Parsing diagnostics until their
        native format is supported.
      </div>
    );
  if (type === "alarms")
    return <div className="notice">{categoryGuidance.alarms}</div>;
  return null;
}

export function EmptyLogCategory({
  type,
  range,
  filtered,
  busy,
  widen,
  navigate,
}: {
  type: string;
  range: string;
  filtered: boolean;
  busy: boolean;
  widen: () => void;
  navigate: (path: string) => void;
}) {
  if (type === "tunnel")
    return (
      <Empty title="Tunnel parsing is not available yet">
        <p>This view cannot display native Tunnel records in this build.</p>
        <button onClick={() => navigate("/logs/parsing")}>
          <FileSearch size={14} /> Open parsing diagnostics
        </button>
      </Empty>
    );
  return (
    <Empty title="No matching events in this time range">
      <p>
        {filtered
          ? "No events match your filter in the selected time range. Widen the range or adjust the filter."
          : "No events were found in the selected time range. Older events may still be available."}
      </p>
      <p>{categoryGuidance[type]}</p>
      <div className="empty-actions">
        {range !== "30d" && (
          <button disabled={busy} onClick={widen}>
            Search last 30 days
          </button>
        )}
        {type === "authentication" && (
          <button onClick={() => navigate("/logs/system?query=subtype%20eq%20auth&range=24h")}>
            View administrator sign-ins
          </button>
        )}
        <button onClick={() => navigate("/administration/setup")}>
          <FileSearch size={14} /> Log forwarding guide
        </button>
      </div>
    </Empty>
  );
}
